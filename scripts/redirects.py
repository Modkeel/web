"""Write _redirects: a 301 from every page's .html and trailing-slash forms to its canonical URL.

Workers static assets' html_handling ("auto-trailing-slash") already serves /guides/x and sends
/guides/x.html and /guides/x/ there, but with a 307 (temporary), so search engines keep the
variants. One explicit line per page, no splats or placeholders: a rule can never match the
canonical URL itself, so nothing loops.

    python scripts/redirects.py           # rewrite _redirects
    python scripts/redirects.py --check   # exit 1 if _redirects is out of date (CI)
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "_redirects"
SKIP = {"scripts", "node_modules"}


def rules(root: Path = ROOT) -> list[str]:
    lines = []
    for f in sorted(root.rglob("*.html")):
        rel = f.relative_to(root)
        if any(p.startswith(".") or p in SKIP for p in rel.parts):
            continue
        path = "/" + rel.as_posix()
        if rel.name == "index.html":
            canon = path[: -len("index.html")]  # "/guides/"
            lines.append(f"{path} {canon} 301")
            if canon != "/":
                lines.append(f"{canon[:-1]} {canon} 301")
        else:
            canon = path[: -len(".html")]  # "/guides/x"
            lines.append(f"{path} {canon} 301")
            lines.append(f"{canon}/ {canon} 301")
    return lines


def render(root: Path = ROOT) -> str:
    return ("# Generated by scripts/redirects.py: one 301 per page variant, to its canonical URL.\n"
            "# Do not edit by hand; run the script after adding or removing a page.\n"
            + "\n".join(rules(root)) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if _redirects is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("_redirects is out of date: run python scripts/redirects.py")
            return 1
        print(f"ok: _redirects covers {text.count(chr(10)) - 2} variants")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {text.count(chr(10)) - 2} redirects")
    return 0


if __name__ == "__main__":
    sys.exit(main())
